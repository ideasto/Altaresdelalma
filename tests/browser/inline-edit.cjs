// Run against a production build: ECOS_TEST_BASE_URL=http://127.0.0.1:3100 node tests/browser/inline-edit.cjs
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.ECOS_TEST_BASE_URL || 'http://127.0.0.1:3100';
const out = path.resolve('artifacts/revision-inline');
fs.mkdirSync(out, { recursive: true });
(async () => {
 const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
 const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
 const p = await context.newPage();
 const errors = [];
 p.on('pageerror', e => errors.push(e.message));
 await context.addInitScript(() => {
  if (localStorage.getItem('revision_seed')) return;
  localStorage.setItem('revision_seed','1');
  localStorage.setItem('altares_welcome_seen','1');
  localStorage.setItem('ma_data_v1',JSON.stringify({avatars:[{id:'revision',name:'Papá Jorge',letters:[{id:'l',to:'Papá',date:'2026-11-01',body:'Una carta querida',sign:'Sole'}],cards:[],timeline:[],book:[],gallery:{photos:[],folders:[]},bookMeta:{title:'Nuestro libro',subtitle:'',coverPhoto:'',backText:'',closing:''}}],trash:[]}));
 });
 await p.goto(base+'/espacio/revision', {waitUntil:'networkidle'});
 assert.equal(await p.locator('select').count(),0);
 await p.getByRole('button',{name:'Personalizar vista de Cartas',exact:true}).click();
 await p.getByLabel('Vista favorita de Cartas').selectOption('l');
 await p.getByLabel('Vista favorita de Cartas').waitFor({state:'hidden'});
 await p.goto(base+'/espacio/revision/libro',{waitUntil:'networkidle'});
 await p.getByTestId('libro-cover-edit').click();
 await p.getByTestId('libro-meta-title').fill('Un libro escrito aquí');
 assert.equal(await p.locator('.fixed.inset-0.z-\\[100\\]').count(),0);
 await p.getByTestId('libro-meta-save').click();
 await p.getByTestId('libro-meta-modal').waitFor({state:'hidden'});
 assert.equal(await p.getByTestId('libro-cover-title').innerText(),'Un libro escrito aquí');
 await p.getByTestId('libro-add').click();
 await p.getByTestId('libro-title-input').fill('Un viaje familiar');
 const text='Una historia con canción y corazón. '.repeat(240)+'FIN DEL RELATO';
 await p.getByTestId('libro-text-input').fill(text);
 await p.getByTestId('libro-text-input').pressSequentially(' Continúa.', {delay:5});
 assert.ok((await p.getByTestId('libro-text-input').inputValue()).endsWith(' Continúa.'));
 await p.waitForTimeout(650);
 assert.ok(await p.getByTestId('libro-text-input').evaluate(e=>e.scrollHeight<=e.clientHeight+3));
 await p.setViewportSize({width:390,height:844});
 await p.evaluate(()=>{window.originalPut=IDBObjectStore.prototype.put;IDBObjectStore.prototype.put=function(){throw new DOMException('Prueba','QuotaExceededError')}});
 await p.getByTestId('libro-form-save').click();
 await p.getByTestId('save-fail-notice').waitFor();
 const notice = await p.locator('[data-sonner-toast]').last().boundingBox();
 assert.ok(!notice || (notice.x >= -1 && notice.x + notice.width <= 391), 'Error toast must fit the mobile screen');
 await p.setViewportSize({width:1440,height:1050});
 assert.ok((await p.getByTestId('libro-text-input').inputValue()).includes('FIN DEL RELATO'));
 await p.getByTestId('libro-form-cancel').click();
 await p.getByTestId('libro-add').click();
 await p.getByTestId('draft-recovered').waitFor();
 await p.getByTestId('libro-form-cancel').click();
 await p.getByTestId('libro-add').click();
 await p.getByTestId('draft-apply').click();
 assert.ok((await p.getByTestId('libro-text-input').inputValue()).includes('FIN DEL RELATO'));
 await p.evaluate(()=>{IDBObjectStore.prototype.put=window.originalPut});
 await p.getByTestId('libro-text-input').fill('Ese viaje familiar quedó en nuestras palabras y nuestras fotos.\n\nHoy escribo este recuerdo para tenerlo cerca.');
 await p.waitForTimeout(4500);
 await p.getByTestId('libro-title-input').scrollIntoViewIfNeeded();
 await p.screenshot({path:path.join(out,'pagina-escritorio.png'),fullPage:false});
 await p.setViewportSize({width:390,height:844});
 assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await p.screenshot({path:path.join(out,'pagina-celular.png'),fullPage:false});
 await p.getByTestId('libro-text-input').fill(text+' Continúa.');
 await p.getByTestId('libro-form-save').click();
 await p.getByTestId('libro-form-modal').waitFor({state:'hidden'});
 await p.reload({waitUntil:'networkidle'});
 await p.getByTestId('libro-next').click();
 await p.getByText('FIN DEL RELATO',{exact:false}).waitFor();
 const download = p.waitForEvent('download');await p.getByTestId('libro-pdf').click();
 await (await download).saveAs(path.join(out,'libro.pdf'));
 await p.goto(base+'/espacio/revision',{waitUntil:'networkidle'});
 await p.screenshot({path:path.join(out,'panel-celular.png'),fullPage:true});
 await p.setViewportSize({width:1440,height:1050});
 await p.screenshot({path:path.join(out,'panel-escritorio.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(out,'resultado.json'),JSON.stringify({inlineEditing:true,typingFocus:true,autoGrowingText:true,failedSavePreserved:true,recoveredTwice:true,reload:true,mobileNoOverflow:true,bookPdf:true,errors},null,2));
 await browser.close();console.log('INLINE EDITING, FAILED SAVE, RECOVERY, MOBILE, PDF: PASS');
})().catch(e=>{console.error(e);process.exit(1)});
